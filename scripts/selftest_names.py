#!/usr/bin/env python3
"""build_names.py の needs_review と strip_entity の逆テスト。

作業者の確認が要る施設かどうかを決める関数。MapRoulette は 要確認 が
立った行しかタスクにしないので、ここで立てるかどうかがそのまま
作業者に届くかどうかになる。

固定しているのは、出力に欠けが無い行で 要確認 を立てない点である。
運営主体を除去した行は、除去した文字列が official_name に残り operator も
出していない。元データの英語表記を採用しなかった行は、name と official_name
がどちらも出ている。どちらも作業者が現地で確かめる対象が無い。
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_names import (needs_review, strip_entity,  # noqa: E402
                         looks_like_facility, use_short_name,
                         strip_bracket_notes, strip_hira_notes)

PFX = ["医療法人社団", "医療法人"]
SUF = ["会", "機構", "社団"]
FW = ["病院", "医院", "診療所", "クリニック", "歯科", "センター"]
SPEC = {"内科", "外科", "消化器内科", "歯科"}
OPW = ["市立", "県立"]
ANY = ["国民健康保険"]
BRK = ["医", "有", "株"]
NOTES = {"出張専門", "往診専門", "崎の字は山へんに立・可"}


def strip(name, short=""):
    return strip_entity(name, PFX, SUF, FW, short, SPEC, OPW, ANY, BRK)


def main():
    cases = [
        ("name が空なら立てる", needs_review(""), "yes"),
        ("空白だけの name も空として扱う", needs_review("  "), "yes"),
        ("name があれば立てない", needs_review("札幌厚生病院"), ""),
        ("推定で落とした語があれば立てる",
         needs_review("歯科", "先頭の「楠井」を運営主体とみなした"), "yes"),
    ]

    # strip_entity。先頭トークンを運営主体と推定してよいかを、元データの
    # 略称で確かめる。略称が「落とす語 + 残り」なら施設名の一部である。
    def eq(label, got, want):
        cases.append((label, got, want))

    eq("略称が施設名の一部と示すなら落とさない",
       strip("楠井 歯科", "楠井歯科"), ("楠井 歯科", [], []))
    eq("略称に法人格が残るなら落とす",
       strip("医療法人ことはる 東栄内科クリニック", "医療法人ことはる 東栄内科クリニック"),
       ("東栄内科クリニック", ["医療法人", "ことはる"], ["ことはる"]))
    eq("略称が無ければ従来どおり落とす",
       strip("楠井 歯科", ""), ("歯科", ["楠井"], ["楠井"]))
    eq("診療科そのものは略称に残っていても落とす",
       strip("消化器内科 中畑クリニック", "消化器内科中畑クリニック"),
       ("中畑クリニック", ["消化器内科"], ["消化器内科"]))
    eq("運営主体の語は略称に残っていても落とす",
       strip("市立 風間浦診療所", "市立風間浦診療所"),
       ("風間浦診療所", ["市立"], ["市立"]))
    eq("法人格の除去は推定に数えない",
       strip("医療法人社団祐川整形外科医院", "医療法人社団祐川整形外科医院"),
       ("祐川整形外科医院", ["医療法人社団"], []))

    # 空白を挟まずに前置された法人名。段2の接尾辞の判定は空白区切りの
    # トークンしか見ないので、別の段で先頭から取り去る。
    eq("空白が無くても法人名を落とす",
       strip("医療法人仁泉会朝倉病院"),
       ("朝倉病院", ["医療法人", "仁泉会"], ["仁泉会"]))
    eq("重なった法人名を続けて落とす",
       strip("医療法人天宣会天宣会循環器クリニック"),
       ("循環器クリニック", ["医療法人", "天宣会", "天宣会"],
        ["天宣会天宣会"]))
    eq("続けて落とした語を1つにまとめて記録する",
       strip("医療法人北海道社会事業協会小樽病院")[2],
       ["北海道社会事業協会"])
    eq("施設種別語だけが残るなら落とさない",
       strip("医療法人ちぐさ会クリニック"),
       ("ちぐさ会クリニック", ["医療法人"], []))
    eq("略称が法人名を残すなら落とさない",
       strip("医療法人久保会医院", "久保会医院"),
       ("久保会医院", ["医療法人"], []))
    eq("落とした後に残る記号を取り去る",
       strip("医療法人(社団)児玉医院"),
       ("児玉医院", ["医療法人", "(社団"], ["(社団)"]))
    eq("会館は法人名の切れ目としない",
       strip("医療法人敬仁会館診療所"),
       ("敬仁会館診療所", ["医療法人"], []))
    eq("法人格が無い行では落とさない",
       strip("コスモ調剤薬局 会津店"),
       ("コスモ調剤薬局 会津店", [], []))
    eq("空白をまたぐ語は落とさない",
       strip("医療法人コスモ調剤薬局 会津店"),
       ("コスモ調剤薬局 会津店", ["医療法人"], []))
    eq("会社は法人名の切れ目としない",
       strip("DIC株式会社小牧工場診療所"),
       ("DIC株式会社小牧工場診療所", [], []))
    eq("会立は法人名の切れ目としない",
       strip("医療法人肝属郡医師会立病院"),
       ("肝属郡医師会立病院", ["医療法人"], []))
    eq("会営は法人名の切れ目としない",
       strip("医療法人小松会営薬局"),
       ("小松会営薬局", ["医療法人"], []))
    eq("診療科だけが残るなら落とさない",
       strip("医療法人山室会山室会外科"),
       ("山室会外科", ["医療法人", "山室会"], ["山室会"]))
    eq("接尾辞と同じ1文字では切らない",
       strip("医療法人会田医院"),
       ("会田医院", ["医療法人"], []))
    eq("附属が残るなら落とさない",
       strip("医療法人岩手県済生会附属有芸診療所"),
       ("岩手県済生会附属有芸診療所", ["医療法人"], []))

    # 名称のどこにあっても落とす語。`国民健康保険` は保険者の名で、
    # 自治体名と施設名の間に挟まる。
    eq("名称の途中の保険者名を落とす",
       strip("遠別町国民健康保険診療所"),
       ("遠別町診療所", ["国民健康保険"], []))
    eq("略称に残る保険者名は落とさない",
       strip("えりも町国民健康保険診療所", "えりも町国民健康保険診療所"),
       ("えりも町国民健康保険診療所", [], []))
    eq("落とすと施設種別語だけになるなら落とさない",
       strip("国民健康保険診療所"),
       ("国民健康保険診療所", [], []))
    eq("落とした後の空白を詰める",
       strip("下北医療センター 国民健康保険 大畑診療所"),
       ("下北医療センター 大畑診療所", ["国民健康保険"], []))

    # 括弧に入った法人格の略記。`(医)` は名称の先頭にも末尾にも現れる。
    eq("先頭の括弧の法人格を落とす",
       strip("(医)成心会なりた内科クリニック"),
       ("なりた内科クリニック", ["(医)", "成心会"], ["成心会"]))
    eq("末尾の括弧の法人格を落とす",
       strip("岡本整形外科クリニック(医療法人)"),
       ("岡本整形外科クリニック", ["(医療法人)"], []))
    eq("中身が法人格で始まる括弧は法人名ごと落とす",
       strip("(医療法人真生会)佐藤医院"),
       ("佐藤医院", ["(医療法人真生会)"], []))
    eq("法人格でない括弧は残す",
       strip("(土田整形外科医院)"),
       ("(土田整形外科医院)", [], []))
    eq("括弧を落とした跡の空白を詰める",
       strip("さくら歯科 (有) 本院"),
       ("さくら歯科 本院", ["(有)"], []))

    # 開きと閉じが揃っていない括弧。元データの 正式名称 が `医）` のように
    # 閉じ括弧だけで始まる行があり、対を探す判定では一致しない。
    eq("閉じ括弧だけの法人格の略記を落とす",
       strip("医)工藤整形外科"),
       ("工藤整形外科", ["医)"], []))
    eq("法人格を落とした跡に残る閉じ括弧を取り去る",
       strip("医療法人社団)いのまた循環器科内科"),
       ("いのまた循環器科内科", ["医療法人社団"], []))
    eq("対応する閉じ括弧が無い開き括弧を取り去る",
       strip("医療法人(巡回診療所ヤマナシ"),
       ("巡回診療所ヤマナシ", ["医療法人"], []))
    eq("法人名を落とした跡の開き括弧も取り去る",
       strip("医療法人潮友会(巡回診療所ヤマナシ"),
       ("巡回診療所ヤマナシ", ["医療法人", "潮友会"], ["潮友会"]))
    eq("名称の途中の閉じない括弧は触らない",
       strip("キムデンタルクリニック(D.KIMS D"),
       ("キムデンタルクリニック(D.KIMS D", [], []))
    eq("閉じ括弧を落とすと空になるなら落とさない",
       strip("医)"), ("医)", [], []))

    # 括弧に入った注記。診療形態と字体の説明は施設名ではないので name から
    # 除き、元の文字列は official_name に残る。
    def notes(value):
        return strip_bracket_notes(value, NOTES)

    eq("末尾の診療形態の注記を落とす",
       notes("あおい助産院(出張専門)"), ("あおい助産院", ["(出張専門)"]))
    eq("先頭の診療形態の注記を落とす",
       notes("(出張専門)サエラ助産院"), ("サエラ助産院", ["(出張専門)"]))
    eq("字体の説明を落とす",
       notes("好生堂和\u5d0e医院(崎の字は山へんに立・可)"),
       ("好生堂和\u5d0e医院", ["(崎の字は山へんに立・可)"]))
    eq("一覧に無い括弧書きは残す",
       notes("赤羽歯科(新宿)"), ("赤羽歯科(新宿)", []))
    eq("落とすと空になるなら落とさない",
       notes("(出張専門)"), ("(出張専門)", []))
    eq("落とした跡の空白を詰める",
       notes("大西助産院 (出張専門)"), ("大西助産院", ["(出張専門)"]))

    # フリガナ側の括弧。name から注記を除いた行では、読みも対応させる。
    eq("読みの括弧書きを落とす",
       strip_hira_notes("あおいじょさんいん(しゅっちょうせんもん)"),
       "あおいじょさんいん")
    eq("読みの末尾の空白も詰める",
       strip_hira_notes("いりえ さき (しゅっちょうせんもん)"), "いりえ さき")
    eq("読みが括弧だけなら落とさない",
       strip_hira_notes("(しゅっちょうせんもん)"), "(しゅっちょうせんもん)")
    eq("読みに括弧が無ければそのまま返す",
       strip_hira_notes("あおいじょさんいん"), "あおいじょさんいん")

    # 正式名称に法人名しか入っていない施設。施設名は略称にしかない。
    def fac(v):
        return looks_like_facility(v, FW, SPEC)

    def useshort(name, short):
        return use_short_name(name, short, FW, SPEC)

    eq("診療科で終われば施設名とみなす", fac("環状通東整形外科"), True)
    eq("会で終われば施設名とみなさない", fac("明雪会"), False)
    eq("空文字は施設名とみなさない", fac(""), False)
    eq("正式名称が法人名だけなら略称を使う",
       useshort("明雪会", "環状通東整形外科"), True)
    eq("name が施設名なら略称を使わない",
       useshort("柴田外科", "柴田クリニック"), False)
    eq("分院名で終わる施設名は略称を使わない",
       useshort("宇梶歯科医院本院", "宇梶歯科"), False)
    eq("地名で終わる施設名は略称を使わない",
       useshort("レーベンデンタルクリニック稲城", "レーベンデンタルクリニック"),
       False)
    eq("略称が施設名でなければ使わない",
       useshort("明雪会", "明雪会本部"), False)
    eq("略称が無ければ使わない", useshort("明雪会", ""), False)
    eq("name が略称に含まれるなら使わない",
       useshort("菊地整形外科", "医療法人　菊地整形外科"), False)

    failed = 0
    print("=== build_names.py needs_review 逆テスト ===\n")
    for name, got, want in cases:
        ok = got == want
        if not ok:
            failed += 1
        print(f"  {'PASS' if ok else 'FAIL'}  {name}")
        if not ok:
            print(f"        実際: {got!r}")
            print(f"        期待: {want!r}")
    print(f"\n  {len(cases) - failed}/{len(cases)} 件")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
